/**
 * The credential-free, secret-free summary of every adapter that the frontend needs: auth kind,
 * declared capabilities, where option-chain Greeks come from, the session-login prompts and the
 * fields the user may save. scripts/generate-broker-capabilities.mjs renders it into
 * src/lib/brokerCapabilities.generated.ts; brokerCapabilitiesSnapshot.test.mjs keeps the two in step.
 */
import { createBrokerRegistry } from "./registry.mjs";
import { declaredCapabilities } from "./contract.mjs";

export function buildBrokerCapabilityMeta(registry = createBrokerRegistry()) {
  const out = {};
  for (const id of [...registry.list()].sort()) {
    const a = registry.get(id);
    const caps = a.capabilities ?? {};
    const greeks = caps.optionChain && typeof caps.optionChain === "object" ? caps.optionChain.greeks ?? null : null;
    out[id] = {
      authKind: caps.auth?.kind ?? "apiKeyToken",
      capabilities: declaredCapabilities(a).filter((c) => c !== "auth" && c !== "normaliseError"),
      greeks: greeks === "broker" || greeks === "computed" ? greeks : null,
      credentialFields: [...(a.credentialFields ?? [])],
      loginFields: (caps.auth?.loginFields ?? []).map((f) => ({ key: f.key, label: f.label, kind: f.kind })),
      sessionFields: [...(caps.auth?.sessionFields ?? [])],
    };
  }
  return out;
}

function renderEntries(meta) {
  return Object.entries(meta)
    .map(([id, m]) => {
      const lines = Object.entries(m).map(([k, v]) => `    ${k}: ${JSON.stringify(v)},`);
      return `  ${id}: {\n${lines.join("\n")}\n  },\n`;
    })
    .join("");
}

export function renderBrokerCapabilityModule(meta) {
  return `/**
 * GENERATED by scripts/generate-broker-capabilities.mjs from server/brokers/*.mjs. Do not edit by hand:
 * change the adapter, then run  node scripts/generate-broker-capabilities.mjs
 * (server/brokers/brokerCapabilitiesSnapshot.test.mjs fails when this file is stale).
 */

export type BrokerAuthKind = "apiKeyToken" | "oauthRedirect" | "requestTokenExchange" | "sessionLogin";

export type BrokerCapability =
  | "testConnection" | "instruments" | "expiries" | "optionChain" | "ltp" | "quotes" | "depth" | "historical" | "feed"
  | "positions" | "holdings" | "funds" | "orderBook" | "tradeBook" | "placeOrder" | "modifyOrder" | "cancelOrder";

export interface BrokerAdapterMeta {
  authKind: BrokerAuthKind;
  capabilities: readonly BrokerCapability[];
  /** Where option-chain Greeks come from: the broker's API, or computed locally (Black-Scholes). */
  greeks: "broker" | "computed" | null;
  /** Keys the user may save (never a password, PIN or TOTP value). */
  credentialFields: readonly string[];
  /** Session-login prompts typed per session and never stored (sessionLogin brokers only). */
  loginFields: readonly { key: string; label: string; kind: "secret" | "totp" }[];
  /** Keys a session login returns and the app stores until expiry. */
  sessionFields: readonly string[];
}

export const BROKER_ADAPTER_META: Readonly<Record<string, BrokerAdapterMeta>> = {
${renderEntries(meta)}};
`;
}
